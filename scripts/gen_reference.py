"""Generate the reference pages under docs/reference/ from the code.

    python scripts/gen_reference.py           write the pages
    python scripts/gen_reference.py --check   exit 1 if a page is out of date (CI)

Config from the pydantic models, API from the OpenAPI schema, CLI from argparse.
Generated pages are never edited by hand.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from pydantic import BaseModel

from jogpad.api import create_app
from jogpad.cli import build_parser
from jogpad.config import Config

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by scripts/gen_reference.py. Do not edit by hand. -->\n\n"


def config_page() -> str:
    lines = [
        HEADER,
        "# Configuration\n\n",
        "jogpad reads a TOML file, by default none (all values below apply). "
        "Pass it with `jogpad serve --config jogpad.toml`.\n",
    ]
    defaults = Config()
    for section, field in Config.model_fields.items():
        model = field.annotation
        assert isinstance(model, type) and issubclass(model, BaseModel)
        lines.append(f"\n## `[{section}]`\n\n")
        lines.append("| Key | Default | Description |\n| --- | --- | --- |\n")
        values = getattr(defaults, section).model_dump(mode="json")
        for name, sub in model.model_fields.items():
            default = json.dumps(values[name], ensure_ascii=False)
            if len(default) > 60:
                default = "see below" if name == "keys" else default
            lines.append(f"| `{name}` | `{default}` | {sub.description or ''} |\n")
    keys = defaults.input.model_dump(mode="json")["keys"]
    lines.append("\n## Default keys\n\n| Action | Keys |\n| --- | --- |\n")
    for action, names in keys.items():
        lines.append(f"| `{action}` | {', '.join(f'`{n}`' for n in names)} |\n")
    return "".join(lines)


def api_page() -> str:
    schema = create_app(Config()).openapi()
    lines = [
        HEADER,
        "# HTTP API\n\n",
        "A running instance serves the interactive Swagger UI at `/docs` and ReDoc at "
        "`/redoc`.\n\n",
        "| Method | Path | Summary |\n| --- | --- | --- |\n",
    ]
    for path, methods in sorted(schema["paths"].items()):
        for method, op in methods.items():
            lines.append(f"| `{method.upper()}` | `{path}` | {op.get('summary', '')} |\n")
    return "".join(lines)


def cli_page() -> str:
    # argparse wraps help to the terminal width and formats it slightly differently
    # between Python versions. Fixed width here; CI runs the check on one version.
    os.environ["COLUMNS"] = "88"
    parser = build_parser()
    parts = [HEADER, "# Command line\n\n```text\n", parser.format_help(), "```\n"]
    subparsers = parser._subparsers._group_actions[0].choices  # type: ignore[union-attr]
    for name, sub in subparsers.items():
        parts += [f"\n## `jogpad {name}`\n\n```text\n", sub.format_help(), "```\n"]
    return "".join(parts)


PAGES = {"config.md": config_page, "api.md": api_page, "cli.md": cli_page}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = ap.parse_args()
    stale = []
    for name, build in PAGES.items():
        path = OUT / name
        text = build()
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("Out of date: " + ", ".join(f"docs/reference/{n}" for n in stale))
        print("Run: python scripts/gen_reference.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
